"""Generate the table of Wendland coefficients shipped with the package.

The table holds the exact polynomial coefficients of psi_{nu,k}, derived with sympy
(_wendland_sympy.py), for the parameters used in practice: smoothness k = 1..4, each with
nu = k + 2 .. k + 5, which covers the smallest positive definite nu in up to 9 dimensions.

    uv run python tools/gen_kernels.py           # write the table
    uv run python tools/gen_kernels.py --check   # exit with an error if it is out of date (CI)
"""

import argparse
import importlib.util
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "divergence_free_interpolant"
TABLE = PACKAGE / "_wendland_table.py"


def _load_derivation():
    """The sympy derivation, loaded from its file so that importing the package (which needs
    the table) is not required: the table can be regenerated even when it is missing."""
    spec = importlib.util.spec_from_file_location(
        "_wendland_sympy", PACKAGE / "_wendland_sympy.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.derive_coefficients


SMOOTHNESS = (1, 2, 3, 4)
NU_OFFSETS = (2, 3, 4, 5)

HEADER = '''"""Exact coefficients of the Wendland functions psi_{nu,k} shipped with the package.

Generated by tools/gen_kernels.py from the sympy derivation in _wendland_sympy.py; do not edit.
Regenerate with `uv run python tools/gen_kernels.py` (CI checks that this file is up to date).
"""

from fractions import Fraction

# (nu, k): ascending coefficients c_j of psi_{nu,k}(r) = sum_j c_j r^j on 0 <= r <= 1
WENDLAND_COEFFICIENTS = {
'''


def render() -> str:
    """The table module, formatted with ruff exactly like the committed file."""
    derive_coefficients = _load_derivation()
    lines = [HEADER]
    for k in SMOOTHNESS:
        for nu in (k + offset for offset in NU_OFFSETS):
            terms = ", ".join(
                f"Fraction({c.numerator}, {c.denominator})"
                for c in derive_coefficients(nu, k)
            )
            lines.append(f"    ({nu}, {k}): ({terms},),\n")
    lines.append("}\n")
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(TABLE), "-"],
        input="".join(lines),
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return formatted.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the table is outdated"
    )
    arguments = parser.parse_args()
    text = render()
    if arguments.check:
        if not TABLE.exists() or TABLE.read_text() != text:
            sys.exit(
                f"{TABLE.relative_to(ROOT)} is out of date: run tools/gen_kernels.py"
            )
        print(f"{TABLE.relative_to(ROOT)} is up to date")
        return
    TABLE.write_text(text)
    print(f"wrote {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
